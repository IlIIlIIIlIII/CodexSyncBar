import assert from 'node:assert/strict';
import {weekly, panelUsage, switchable, switchLocal} from '../../gnome/model.js';
const now = Date.now();
const account = value => ({id: 2, usage: {weekly: {remainingPercent: value, resetsAt: new Date(now + 86400000).toISOString()}, updatedAt: new Date(now).toISOString()}});
assert.equal(weekly(account(0), now).value, '0%');
assert.equal(weekly(account(null), now).value, '—');
assert.equal(weekly(account(NaN), now).value, '—');
assert.equal(weekly(account(68), now).tone, 'healthy');
assert.equal(weekly(account(5), now).tone, 'warning');
assert.equal(weekly({...account(null), needsLogin: true}, now).caption, '재로그인 필요');
assert.match(weekly(account(68), now + 700000).caption, /이전 수치/);
assert.match(weekly(account(68), now, true).caption, /연결 실패/);
assert.equal(switchable(account(68), {activeProfileId: 2}), false);
assert.equal(switchable(account(68), {activeProfileId: 1, isBusy: true}), false);
assert.equal(switchable({...account(68), needsLogin: true}, {activeProfileId: 1}), false);
assert.equal(switchable(account(68), {activeProfileId: 1}), true);
const panelSnapshot = {accounts: [{...account(84), id: 1}, account(68)], activeProfileId: 2};
assert.equal(panelUsage(panelSnapshot, now).text, '주간 68%');
assert.equal(panelUsage({...panelSnapshot, activeProfileId: 1}, now).text, '주간 84%');
assert.equal(panelUsage({...panelSnapshot, activeProfileId: 99}, now).text, '주간 —');
assert.equal(panelUsage({...panelSnapshot, accounts: [account(0)]}, now).text, '주간 0%');
assert.equal(panelUsage({...panelSnapshot, accounts: [account(100)]}, now).text, '주간 100%');
assert.equal(panelUsage(panelSnapshot, now, true).text, '주간 —');
assert.equal(panelUsage(panelSnapshot, now + 700000).text, '주간 —');
assert.equal(panelUsage({...panelSnapshot, accounts: [{...account(68), needsLogin: true}]}, now).text, '주간 —');
assert.match(panelUsage(panelSnapshot, now).description, /이 PC 주간 잔여량 68%/);
const calls = [];
const call = async (method, params) => {
    calls.push([method, params]);
    return method === 'preview' ? {profileId: 2, previewId: 'p', canApply: true, targets: [{id: 'local', included: true}, {id: 'ssh:dev', included: false}]} : {id: 'o'};
};
await switchLocal(call, 2, 'request');
assert.deepEqual(calls, [['preview', {profileId: 2, deviceId: 'local'}], ['apply', {previewId: 'p', requestId: 'request'}]]);
let applied = false;
await assert.rejects(switchLocal(async method => {
    if (method === 'apply') applied = true;
    return {profileId: 2, canApply: true, targets: [{id: 'local', included: true}, {id: 'ssh:dev', included: true}]};
}, 2, 'request'), /이 PC/);
assert.equal(applied, false);
await assert.rejects(switchLocal(async () => ({canApply: false, targets: [], blockingReason: '복구 필요'}), 2, 'request'), /복구 필요/);
console.log('Tray model/command assertions passed');
